// SendMessage_stub: reached through a send site's target word on an
// inline-cache miss.  On entry [rsp] is the send's return PC, which IS the
// sendDesc; the receiver and arguments sit in the sender's outgoing area
// ([rsp+8] up), and rbp is the sender's frame.  The ordinary prologue
// makes a proper frame record ({sender fp, send-site pc}) that frame
// walks during the lookup can traverse.  Call the C lookup (which
// compiles and rebinds the cache), then tail-jump to the returned entry
// point with [rsp] back at the sendDesc so the callee sees a fresh call.
static void generate_SendMessage_stub(Assembler* a) {
  a->Comment("SendMessage_stub");
  a->push(FrameReg);
  a->mov(FrameReg, SP);
  a->load(rdi, FrameReg, 1 * oopSize); // ic = the sendDesc (pushed retPC)
  a->mov(rsi, FrameReg);               // lookupFrame = this record
  a->load(rdx, FrameReg, 2 * oopSize); // receiver from sender's outgoing area
  a->mov(rcx, PerformSelectorLoc);     // dynamic selector (perform sends; r12)
  a->mov(r8,  PerformDelegateeLoc);    // dynamic delegatee (r13)
  a->load(r9, FrameReg, 3 * oopSize);  // arg1 from the outgoing area
  a->call_literal((void*)&SendMessage, VMAddressOperand);
  a->mov(Temp2, ResultReg);            // target entry point
  a->pop(FrameReg);                    // rsp -> the sendDesc retPC again
  a->jmp_reg(Temp2);
}

